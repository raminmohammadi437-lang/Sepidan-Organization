const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let observer;

function translateTextNode(node, language) {
  if (!node.nodeValue?.trim()) return;
  const parent = node.parentElement;
  if (!parent || parent.closest('script, style, noscript, [data-i18n-ignore]')) return;
  if (!originalText.has(node)) originalText.set(node, node.nodeValue);
  const english = originalText.get(node);
  const trimmed = english.trim();
  const dynamicReplacement = language === 'fa' ? translateDynamicPhrase(trimmed) : null;
  const replacement = language === 'fa' ? (dari[trimmed] || dynamicReplacement) : trimmed;
  if (!replacement) return;
  const next = english.replace(trimmed, replacement);
  if (node.nodeValue !== next) node.nodeValue = next;
}

function translateDynamicPhrase(english) {
  const minutes = english.match(/^(\d+) minutes ago$/);
  if (minutes) return `${minutes[1]} دقیقه پیش`;
  const room = english.match(/^Room (\d+)$/);
  if (room) return `اتاق ${room[1]}`;
  const lab = english.match(/^Lab (\d+)$/);
  if (lab) return `لابراتوار ${lab[1]}`;
  return null;
}

function translateElementAttributes(element, language) {
  const attributes = ['placeholder', 'aria-label', 'title', 'alt'];
  if (!originalAttributes.has(element)) originalAttributes.set(element, {});
  const stored = originalAttributes.get(element);
  attributes.forEach((attribute) => {
    const value = element.getAttribute?.(attribute);
    if (!value) return;
    if (!stored[attribute]) stored[attribute] = value;
    const english = stored[attribute];
    const next = language === 'fa' ? (dari[english] || english) : english;
    if (value !== next) element.setAttribute(attribute, next);
  });
}

function translateRoot(root, language) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root, language);
    return;
  }
  if (!(root instanceof Element) && root !== document.body) return;
  if (root instanceof Element) translateElementAttributes(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) translateTextNode(node, language);
  root.querySelectorAll?.('[placeholder], [aria-label], [title], [alt]').forEach((element) => translateElementAttributes(element, language));
}

function refreshToggleLabels(language) {
  document.querySelectorAll('[data-language-toggle]').forEach((button) => {
    button.dataset.i18nIgnore = '';
    const label = language === 'fa' ? 'English' : 'دری';
    const ariaLabel = language === 'fa' ? 'Switch to English' : 'تغییر زبان به دری';
    const buttonLanguage = language === 'fa' ? 'en' : 'fa';
    const buttonDirection = language === 'fa' ? 'ltr' : 'rtl';
    const labelElement = button.querySelector('[data-language-label]');
    if (labelElement && labelElement.textContent !== label) labelElement.textContent = label;
    else if (button.textContent !== label) button.textContent = label;
    if (button.getAttribute('aria-label') !== ariaLabel) button.setAttribute('aria-label', ariaLabel);
    if (button.getAttribute('lang') !== buttonLanguage) button.setAttribute('lang', buttonLanguage);
    if (button.getAttribute('dir') !== buttonDirection) button.setAttribute('dir', buttonDirection);
  });
}

function applyLanguage(language) {
  const nextLanguage = language === 'fa' ? 'fa' : 'en';
  document.documentElement.lang = nextLanguage === 'fa' ? 'fa-AF' : 'en';
  document.documentElement.dir = nextLanguage === 'fa' ? 'rtl' : 'ltr';
  document.title = nextLanguage === 'fa' ? (dari[document.title] || document.title) : (document.title.includes(' | ') ? Object.keys(dari).find((key) => dari[key] === document.title) || document.title : document.title);
  translateRoot(document.body, nextLanguage);
  refreshToggleLabels(nextLanguage);
  localStorage.setItem('siteLanguage', nextLanguage);
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { language: nextLanguage } }));
}

function initializeI18n() {
  const language = localStorage.getItem('siteLanguage') === 'fa' ? 'fa' : 'en';
  document.querySelectorAll('[data-language-toggle]').forEach((button) => {
    button.addEventListener('click', () => applyLanguage(document.documentElement.dir === 'rtl' ? 'en' : 'fa'));
  });
  applyLanguage(language);
  observer?.disconnect();
  observer = new MutationObserver((mutations) => {
    const activeLanguage = document.documentElement.dir === 'rtl' ? 'fa' : 'en';
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => translateRoot(node, activeLanguage));
      if (mutation.type === 'characterData') translateTextNode(mutation.target, activeLanguage);
    });
    refreshToggleLabels(activeLanguage);
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

function translatePhrase(english) {
  return document.documentElement.dir === 'rtl' ? (dari[english] || english) : english;
}

window.SepidanI18n = Object.freeze({
  applyLanguage,
  initializeI18n,
  translatePhrase
});
